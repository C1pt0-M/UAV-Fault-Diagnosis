def test_rng_isolation_actual_three_epoch_training_with_extra_inference_on_off(tmp_path):
    x = torch.randn(6, 26, 150, generator=torch.Generator().manual_seed(999))
    y = torch.tensor([0, 0, 1, 0, 0, 1])
    dataset = TensorDataset(x, y)
    results = []
    for extra in (False, True):
        torch.manual_seed(42)
        np.random.seed(42)
        model = s.build_variant('mstca')
        s.initialize_variant(model, 'mstca', 42)
        sampler = WeightedRandomSampler(torch.ones(6, dtype=torch.float64), 6, replacement=True,
            generator=torch.Generator().manual_seed(53))
        loader = DataLoader(dataset, batch_size=512, sampler=sampler, num_workers=0,
            generator=torch.Generator().manual_seed(143))
        out = tmp_path / str(extra)
        out.mkdir()
        history, inner, held = train.trajectory(model, loader, train.inference_loader(dataset, 42),
            train.inference_loader(dataset, 42), train.inference_loader(dataset, 42), out, 3, 'cpu',
            record_predictions=extra)
        results.append(([h['state_digest'] for h in history], torch.random.get_rng_state().clone()))
        assert [row['lr'] for row in history] == [s.get_warmup_cosine_lr(i, 5, 100, 3e-4, 1e-6) for i in range(3)]
        if extra:
            assert inner.shape == held.shape == (3, 6)
        for epoch in range(1, 4):
            state = torch.load(out / f'checkpoints/epoch_{epoch}.pt', weights_only=True)
            assert s._state_digest(state) == history[epoch - 1]['state_digest']
    assert results[0][0] == results[1][0]
    assert torch.equal(results[0][1], results[1][1])



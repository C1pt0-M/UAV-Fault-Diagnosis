@pytest.mark.parametrize('local,skip_case', [(True, False), (False, False), (True, True)])
def test_preflight_local_no_gpu_or_ssh_and_formal_two_fully_mocked_probes(tmp_path, monkeypatch, local, skip_case):
    monkeypatch.setattr(train, 'OUTPUT_ROOT', tmp_path)
    monkeypatch.setattr(train, 'load_protocol', lambda *a: ({}, {}))
    env = {'torch': '2.5.1+cu124', 'numpy': '2.1.3', 'torch_cuda': '12.4', 'cuda_available': True,
           'cublas_workspace_config': ':4096:8', 'aten_cpu_capability': 'default'}
    monkeypatch.setattr(train, 'environment', lambda: env)
    monkeypatch.setattr(train, 'verify_data', lambda *a, **kw: {'matched_sha256': {}, 'skipped_sha256': []})
    monkeypatch.setattr(s, 'read_ledger', lambda *a: None)
    monkeypatch.setattr(s, 'fold_sizes', lambda *a: {})
    monkeypatch.setattr(preflight, 'check_cpu_smoke', lambda root=None: {'status': 'PASS', 'root': str(root)})
    commands, probes = [], []
    def command(cmd, **kwargs):
        commands.append(cmd)
        assert cmd[0] != 'ssh'
        if cmd[0] == sys.executable:
            if local:
                assert kwargs['env']['CUDA_VISIBLE_DEVICES'] == ''
            xml = Path(next(v.split('=', 1)[1] for v in cmd if v.startswith('--junitxml=')))
            suite = preflight.ET.Element('testsuite')
            for i in range(12):
                preflight.ET.SubElement(suite, 'testcase', name=f'test_full_state_digest_golden[mock-{i}]')
            for i in (45, 46):
                preflight.ET.SubElement(suite, 'testcase', name=f'test_new_golden[{i}]')
            if skip_case:
                case = preflight.ET.SubElement(suite, 'testcase', name='legacy_basetemp_case')
                preflight.ET.SubElement(case, 'skipped', type='pytest.skip')
            preflight.ET.ElementTree(suite).write(xml, encoding='utf-8')
        else:
            assert not local and cmd[0] in ('git', 'nvidia-smi')
        return SimpleNamespace(returncode=0, stdout='mock evidence', stderr='')
    monkeypatch.setattr(preflight.subprocess, 'run', command)
    def probe(args, *, probe_epochs):
        probes.append(args)
        assert probe_epochs == 2 and args.seed == 42 and args.fold == 0
        return {'checkpoint_state_digests': {'1': 'a' * 64, '2': 'b' * 64}}
    monkeypatch.setattr(train, 'run', probe)
    args = SimpleNamespace(output=tmp_path / 'preflight', local=local, data=tmp_path / 'unused',
        protocol=train.DEFAULT_PROTOCOL, cpu_smoke_root=train.SMOKE_ROOT / 'fresh_fixture')
    if skip_case:
        with pytest.raises(RuntimeError, match='zero skipped'):
            preflight.preflight(args)
        assert not probes
        return
    result = preflight.preflight(args)
    assert result['cpu_smoke']['root'] == str(args.cpu_smoke_root)
    assert result['pytest_summary']['skipped'] == 0
    assert result['golden_tests_passed'] == 14
    assert result['formal_clearance'] == (not local)
    assert len(probes) == (0 if local else 2)
    assert result['remote_connection'] == 'OPERATOR_SIDE_ONLY_NOT_RUN'



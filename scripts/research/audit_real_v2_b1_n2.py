def recover_events(meta,arrays,p,onset_th):
    aggregate,record,_=original_functions();captured={}
    def capture(*a,**k):
        value=aggregate(*a,**k);captured.update(value);return value
    result=record(meta,arrays,p,onset_th,aggregate=capture)
    times=arrays['timestamp_us']/1e6;normal=arrays['row_label_valid'] & (arrays['reference_state']==0) & np.isfinite(p)
    selected=[]
    for event in captured['finalized_events']:
        mask=(times>=event['start_t']) & (times<=event['end_t'])
        if result['onset_s'] is not None and event['end_t']<result['onset_s'] and mask.any() and normal[mask].all():
            # Wall-clock emission metadata is newly generated by replay, not historical evidence.
            selected.append({k:event[k] for k in ['start_t','end_t','confirmed_t','emitted_t','emission_reason']})
    assert len(selected)==result['N2_events']
    return result,selected


def overlap_components(rows):
    adj={v['event_id']:set() for v in rows};by={v['event_id']:v for v in rows}
    for i,a in enumerate(rows):
        for b in rows[i+1:]:
            if a['case_uid']==b['case_uid'] and a['arm']!=b['arm'] and max(a['start_s'],b['start_s'])<=min(a['end_s'],b['end_s']):
                adj[a['event_id']].add(b['event_id']);adj[b['event_id']].add(a['event_id'])
    seen=set();groups=[]
    for key in adj:
        if key in seen:continue
        pending=[key];component=[]
        while pending:
            item=pending.pop()
            if item in seen:continue
            seen.add(item);component.append(item);pending.extend(adj[item]-seen)
        groups.append({'component':len(groups)+1,'case_uid':by[key]['case_uid'],'event_ids':sorted(component),
                       'R':sum(by[v]['arm']=='R' for v in component),'S_plus_R':sum(by[v]['arm']=='S_plus_R' for v in component),
                       'shared':len({by[v]['arm'] for v in component})==2})
    return groups


def summarize(values):
    a=np.asarray(values);a=a[np.isfinite(a)]
    if len(a)<25:return {'n':len(a),'median':None,'iqr':None,'p05':None,'p95':None,'median_abs_delta':None,'zero_delta_fraction':None}
    q=np.quantile(a,[.05,.25,.5,.75,.95]);delta=np.diff(a)
    return {'n':len(a),'median':float(q[2]),'iqr':float(q[3]-q[1]),'p05':float(q[0]),'p95':float(q[4]),
            'median_abs_delta':float(np.median(np.abs(delta))) if len(delta) else None,
            'zero_delta_fraction':float(np.mean(delta==0)) if len(delta) else None}


def motion_signals(raw):
    q=raw[:,15:19];norm=np.linalg.norm(q,axis=1);z=np.divide(q[:,1]**2+q[:,2]**2,norm**2,out=np.full(len(raw),np.nan),where=norm>0)
    return {'gyro_norm':np.linalg.norm(raw[:,8:11],axis=1),'accel_norm':np.linalg.norm(raw[:,11:14],axis=1),
            'horizontal_speed':np.linalg.norm(raw[:,19:21],axis=1),'vertical_velocity':raw[:,21],
            'tilt_deg':np.degrees(np.arccos(np.clip(1-2*z,-1,1))),'quaternion_norm':norm}


def interval_mask_us(timestamps_us,interval):
    lo,hi=(int(round(float(v)*1e6)) for v in interval)
    return (timestamps_us>=lo)&(timestamps_us<=hi)


def sample_metrics(arrays,interval,columns):
    mask=interval_mask_us(arrays['timestamp_us'],interval) & arrays['row_input_valid']
    raw=arrays['canonical_rows'].copy();raw[:,25]=np.linalg.norm(raw[:,11:14],axis=1)
    values={name:raw[:,i] for i,name in enumerate(columns)};values.update(motion_signals(raw))
    # Derivative checks must not bridge invalid rows or separated pieces.
    result={}
    for key,value in values.items():
        kept=np.where(mask,value,np.nan);v=summarize(kept)
        contiguous=mask[:-1]&mask[1:]&np.isfinite(value[:-1])&np.isfinite(value[1:])
        delta=np.diff(value)[contiguous]
        v['median_abs_delta']=float(np.median(np.abs(delta))) if len(delta)>=24 else None
        v['zero_delta_fraction']=float(np.mean(delta==0)) if len(delta)>=24 else None
        result[key]=v
    return result


def install_guard(allowed):
    allowed={Path(p).resolve():v for p,v in allowed.items()};audit={'opens':[],'blocked':[]}
    def guard(event,args):
        if event in ('socket.connect','socket.connect_ex'):raise PermissionError('N2 audit forbids network')
        if event=='import' and str(args[0]).split('.')[0] in ('sklearn','torch'):
            raise PermissionError('N2 audit does not import training/inference modules')
        if event!='open' or not isinstance(args[0],(str,bytes,os.PathLike)):return
        path=Path(os.fsdecode(args[0])).resolve();mode=args[1] or '';flags=args[2] or 0
        write=any(c in mode for c in 'wax+') or bool(flags & (os.O_WRONLY|os.O_RDWR|os.O_CREAT|os.O_TRUNC|os.O_APPEND))
        protected=path.is_relative_to(Path('D:/UAV-Data').resolve()) or path.is_relative_to(Path('D:/RflyMAD').resolve()) or path.is_relative_to(B1.resolve()) or path.is_relative_to(BAGS.resolve())
        other_locked=path.is_relative_to((ROOT/'artifacts/internal_test_final_v1').resolve()) or path.is_relative_to((ROOT/'artifacts/ens_internal_test_v1_20261105').resolve())
        if other_locked or (protected and (write or path not in allowed)) or path.suffix.lower() in ('.pkl','.pt','.pth'):
            audit['blocked'].append(str(path));raise PermissionError('N2 audit boundary: '+str(path))
        if path in allowed:
            item={'path':str(path),**allowed[path]};audit['opens'].append(item)
            with(OUT/'input_access.jsonl').open('a',encoding='utf-8',newline='\n') as f:f.write(json.dumps(item,ensure_ascii=False)+'\n');f.flush();os.fsync(f.fileno())
    sys.addaudithook(guard);return audit


def npz(path,expected=None):
    raw=Path(path).read_bytes()
    if expected is not None and hashlib.sha256(raw).hexdigest()!=expected:raise ValueError('Saved input SHA mismatch: '+str(path))
    with np.load(io.BytesIO(raw),allow_pickle=False) as z:return {k:z[k] for k in z.files}


